import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
const server = spawn('npx', ['vite', 'preview', '--port', '4999', '--strictPort'], { cwd: '/home/claude/mathe-jahrmarkt' });
await new Promise((r) => setTimeout(r, 2500));
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const page = await b.newPage({ viewport: { width: 390, height: 800 } });
page.on('console', (m) => console.log('console', m.type(), m.text()));
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto('http://localhost:4999/');
await page.getByPlaceholder('Spitzname').fill('Alex');
await page.getByPlaceholder('Spitzname').press('Enter');
await page.getByRole('button', { name: 'Los geht’s' }).click();
await page.waitForTimeout(2000);
await page.screenshot({ path: process.argv[2] });
await b.close(); server.kill();
